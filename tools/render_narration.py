"""Render original lesson text with the UK Piper voice referenced by docs/AUDIO.md."""
import json
import subprocess
import sys
from pathlib import Path

import lameenc
import numpy as np
import onnxruntime as ort
import piper
from piper.config import PiperConfig
from piper.voice import PiperVoice

root = Path(__file__).resolve().parents[1]
model = Path(sys.argv[1]).resolve()
options = ort.SessionOptions()
options.intra_op_num_threads = 2
options.inter_op_num_threads = 1
voice = PiperVoice(
    config=PiperConfig.from_dict(json.loads(Path(str(model) + ".json").read_text(encoding="utf-8"))),
    session=ort.InferenceSession(str(model), sess_options=options, providers=["CPUExecutionProvider"]),
    espeak_data_dir=Path(piper.__file__).parent / "espeak-ng-data",
    download_dir=model.parent,
)
lessons = json.loads(subprocess.check_output(
    ["node", "--input-type=module", "-e", "import {lessons} from './content/curriculum.mjs'; console.log(JSON.stringify(lessons))"],
    cwd=root, encoding="utf-8"
))
directory = root / "assets" / "listening"
directory.mkdir(exist_ok=True)
rate = voice.config.sample_rate
manifest = {}
for lesson in lessons:
    frames, ranges, count = [], [], 0
    for text in lesson["chunks"]:
        parts = [piece.audio_int16_array for piece in voice.synthesize(text)]
        chunk = np.concatenate(parts)
        if not len(chunk) or not np.max(np.abs(chunk.astype(float))):
            raise RuntimeError(f"Empty audio in lesson {lesson['day']}")
        # Short natural breaks between thought groups, with boundaries from actual sample counts.
        frames.extend([chunk, np.zeros(round(rate * 0.12), dtype=np.int16)])
        ranges.append([round(count / rate, 3), round((count + len(chunk)) / rate, 3)])
        count += len(chunk) + len(frames[-1])
    encoder = lameenc.Encoder()
    encoder.set_in_sample_rate(rate)
    encoder.set_channels(1)
    encoder.set_bit_rate(48)
    encoder.set_quality(2)
    filename = f"day-{lesson['day']:02}.mp3"
    encoded = encoder.encode(np.concatenate(frames).astype("<i2").tobytes()) + encoder.flush()
    (directory / filename).write_bytes(encoded)
    manifest[lesson["day"]] = {"file": "./assets/listening/" + filename, "segments": ranges}
    print(f"Day {lesson['day']}: {count/rate:.1f}s, {len(encoded)} bytes", flush=True)
(root / "content" / "narration.mjs").write_text(
    "// Generated by tools/render_narration.py from the lesson chunks.\nexport const narration = "
    + json.dumps(manifest, indent=2) + ";\n", encoding="utf-8"
)

