// Regenerate the self-contained offline shell after changing any shipped asset.
import {readdir,readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const root=fileURLToPath(new URL('../',import.meta.url));
async function walk(dir) {
  const entries=await readdir(path.join(root,dir),{withFileTypes:true});
  return (await Promise.all(entries.map(e=>e.isDirectory()?walk(dir+'/'+e.name):dir+'/'+e.name))).flat();
}
const names=['index.html','style.css','app.mjs','manifest.webmanifest','docs/AUDIO.md',...await walk('lib'),...await walk('content'),...await walk('assets')].sort();
const hash=createHash('sha256');
for(const name of names){hash.update(name);hash.update(await readFile(path.join(root,name)));}
const version=hash.digest('hex').slice(0,16);
const source=`// Generated by node tools/build-sw.mjs
const prefix='english90-coach:'+self.registration.scope+':';
const cacheName=prefix+'${version}';
const files=${JSON.stringify(names)};
const urls=new Set(files.map(file=>new URL(file,self.registration.scope).href));
self.addEventListener('install',event=>event.waitUntil((async()=>{
 const c=await caches.open(cacheName);
 try {await c.addAll(files.map(file=>new Request(new URL(file,self.registration.scope),{cache:'reload'})));}
 catch(error){await caches.delete(cacheName);throw error;}
})()));
self.addEventListener('message',event=>{if(event.data==='ACTIVATE')event.waitUntil(self.skipWaiting());});
self.addEventListener('activate',event=>event.waitUntil((async()=>{
 for(const k of await caches.keys())if(k.startsWith(prefix)&&k!==cacheName)await caches.delete(k);
 await self.clients.claim();
})()));
self.addEventListener('fetch',event=>{
 const r=event.request;
 if(r.method!=='GET')return;
 const url=new URL(r.url);
 const home=self.registration.scope;
 const key=r.mode==='navigate'&&(url.href.split(/[?#]/)[0]===home||url.pathname===new URL('index.html',home).pathname)?new URL('index.html',home).href:url.href;
 if(!urls.has(key))return;
 event.respondWith((async()=>{
   const c=await caches.open(cacheName),hit=await c.match(key);
   if(!hit)return fetch(r);
   if(r.headers.has('range')&&key.includes('/assets/listening/')){
     const m=/^bytes=(\\d+)-(\\d*)$/.exec(r.headers.get('range'));
     if(!m)return hit;
     const data=await hit.arrayBuffer(),start=Number(m[1]),end=m[2]?Math.min(data.byteLength-1,Number(m[2])):data.byteLength-1;
     if(start>end)return new Response(null,{status:416,headers:{'Content-Range':'bytes */'+data.byteLength}});
     return new Response(data.slice(start,end+1),{status:206,headers:{'Content-Type':hit.headers.get('Content-Type')||'audio/mpeg','Content-Range':'bytes '+start+'-'+end+'/'+data.byteLength,'Accept-Ranges':'bytes','Content-Length':String(end-start+1)}});
   }
   return hit;
 })());
});\n`;
await writeFile(path.join(root,'sw.js'),source);
console.log(names.length+' offline assets, '+version);
